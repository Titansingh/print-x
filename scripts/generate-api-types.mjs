#!/usr/bin/env node
/**
 * Generates TypeScript types from the backend-owned OpenAPI document.
 *
 * Source (first match wins):
 *   1. CLI argument:      pnpm generate:api -- ./openapi.local.yaml
 *   2. API_SPEC_PATH env: local, versioned spec file (JSON or YAML)
 *   3. API_SPEC_URL env:  published spec URL, e.g. https://api.example.test/openapi/v1.json
 *
 * Output: packages/api-types/src/generated/{schema,meta}.ts
 * See docs/integration/api-contract.md for the full workflow.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = resolve(repoRoot, "packages/api-types/src/generated");

const rawSource =
  process.argv.slice(2).find((arg) => arg !== "--") ??
  process.env.API_SPEC_PATH ??
  process.env.API_SPEC_URL;

if (!rawSource) {
  console.error(
    [
      "No OpenAPI source provided.",
      "Set API_SPEC_URL (published spec) or API_SPEC_PATH (local file), or pass a path:",
      "  API_SPEC_URL=https://<backend-host>/openapi.json pnpm generate:api",
      "  pnpm generate:api -- ./openapi.local.yaml",
      "The committed placeholder types are left unchanged.",
    ].join("\n"),
  );
  process.exit(1);
}

const isRemote = /^https?:\/\//i.test(rawSource);
const sourceUrl = isRemote ? new URL(rawSource) : pathToFileURL(resolve(process.cwd(), rawSource));

/** Strip credentials and query strings (e.g. tokens) before logging or committing. */
function describeSource(url) {
  if (url.protocol === "file:") {
    const abs = fileURLToPath(url);
    return abs.startsWith(repoRoot) ? abs.slice(repoRoot.length + 1) : abs;
  }
  return `${url.protocol}//${url.host}${url.pathname}`;
}

const safeSource = describeSource(sourceUrl);
console.log(`Generating API types from ${safeSource} ...`);

let ast;
try {
  ast = await openapiTS(sourceUrl);
} catch (error) {
  console.error(`Failed to load or parse the OpenAPI document: ${error?.message ?? error}`);
  process.exit(1);
}

const banner = [
  "/**",
  " * GENERATED by scripts/generate-api-types.mjs from the backend OpenAPI document.",
  ` * Source: ${safeSource}`,
  " * Do not edit by hand. Regenerate with `pnpm generate:api`.",
  " */",
  "",
].join("\n");

const schema = banner + astToString(ast);

if (!/export (interface|type) paths\b/.test(schema)) {
  console.error("Generated output does not export `paths`; refusing to overwrite types.");
  process.exit(1);
}

const meta = [
  "/** Written by scripts/generate-api-types.mjs. Do not edit by hand. */",
  "export const apiContractMeta = {",
  "  isPlaceholder: false,",
  `  source: ${JSON.stringify(safeSource)},`,
  "} as const satisfies { isPlaceholder: boolean; source: string | null };",
  "",
].join("\n");

await mkdir(outDir, { recursive: true });
await writeFile(resolve(outDir, "schema.ts"), schema);
await writeFile(resolve(outDir, "meta.ts"), meta);

console.log("Wrote packages/api-types/src/generated/schema.ts and meta.ts");
console.log("Next: run `pnpm typecheck` to surface any contract changes in the apps.");
